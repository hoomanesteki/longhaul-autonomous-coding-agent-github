"""The schema the console is built from (LH-801).

`console/openapi.json` is generated by `make api-types` and the console's typed client is made
from it (LH-802). The file has to be the schema of the app as it is now, or the client would be
built from a stale copy. The routes are the ones the plan names, each with a stable operation
id, which is the name of the function in the generated client.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from longhaul.api.app import create_app, openapi_schema, render_openapi

pytestmark = [pytest.mark.unit, pytest.mark.phase8]

ROOT = Path(__file__).resolve().parents[2]
SCHEMA_FILE = ROOT / "console" / "openapi.json"

# The endpoints of plan story LH-801.
ENDPOINTS = {
    ("get", "/api/tasks"),
    ("get", "/api/tasks/{task_id}"),
    ("get", "/api/tasks/{task_id}/timeline"),
    ("get", "/api/tasks/{task_id}/turns/{turn_index}"),
    ("get", "/api/tasks/{task_id}/tool-calls/{call_id}/output"),
    ("post", "/api/tasks/{task_id}/approve-plan"),
    ("post", "/api/tasks/{task_id}/reject-plan"),
    ("post", "/api/tasks/{task_id}/hint"),
    ("post", "/api/tasks/{task_id}/budget"),
    ("post", "/api/tasks/{task_id}/cancel"),
    ("get", "/api/memory"),
    ("post", "/api/memory/{item_id}/approve"),
    ("post", "/api/memory/{item_id}/reject"),
    ("get", "/api/repos"),
    ("get", "/healthz"),
    ("get", "/metrics"),
}


def test_the_schema_file_is_the_schema_of_the_app() -> None:
    assert SCHEMA_FILE.read_text(encoding="utf-8") == render_openapi(), (
        "console/openapi.json is out of date. Run `make api-types` and commit the result."
    )


def test_the_app_has_the_endpoints_of_the_plan_and_no_others() -> None:
    schema = openapi_schema()

    found = {(method, path) for path, ops in schema["paths"].items() for method in ops}

    assert found == ENDPOINTS


def test_every_operation_has_a_unique_readable_id() -> None:
    schema = openapi_schema()

    ids = [op["operationId"] for ops in schema["paths"].values() for op in ops.values()]

    assert len(ids) == len(set(ids)) == len(ENDPOINTS)
    assert all(i.isidentifier() and not i.startswith("api_") for i in ids), ids


def test_the_timeline_items_are_told_apart_by_kind() -> None:
    schema = openapi_schema()

    page = schema["components"]["schemas"]["TimelinePage"]
    items = page["properties"]["items"]["items"]

    assert items["discriminator"]["propertyName"] == "kind"
    assert set(items["discriminator"]["mapping"]) == {"event", "turn", "tool_call"}


def test_the_schema_is_stable_json() -> None:
    first = render_openapi()

    assert first == render_openapi()
    assert first.endswith("\n")
    assert json.loads(first)["info"]["title"] == "Longhaul console API"


def test_the_app_builds_without_a_database() -> None:
    # Nothing connects until the app starts. The schema is dumped this way, in CI.
    app = create_app()

    assert not hasattr(app.state, "context")
    assert {"/healthz", "/metrics", "/api/tasks"} <= set(app.openapi()["paths"])
